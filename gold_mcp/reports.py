"""HTML / Markdown report generator — Ultra tier.

Produces standalone HTML tearsheets and Markdown briefings that
aggregate the gold-mcp tool outputs into a polished, human-readable
artifact. Files are written to disk and the path is returned.
"""
from __future__ import annotations

import os
import time
from html import escape
from pathlib import Path


def _reports_dir() -> Path:
    raw = os.environ.get("GOLD_MCP_REPORTS_DIR", "").strip()
    base = Path(raw).expanduser() if raw else Path.home() / ".cache" / "gold-mcp" / "reports"
    base.mkdir(parents=True, exist_ok=True)
    return base


